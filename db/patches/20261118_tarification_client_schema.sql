-- The pricing routes also run on databases bootstrapped only from this patch set.
-- Existing installations can already have the historical table and its data.
CREATE TABLE IF NOT EXISTS public.tarification_client (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id varchar NOT NULL REFERENCES public.clients(client_id) ON DELETE RESTRICT,
  remise_globale_pct numeric NOT NULL DEFAULT 0 CHECK (remise_globale_pct BETWEEN 0 AND 100),
  escompte_pct numeric NOT NULL DEFAULT 0 CHECK (escompte_pct BETWEEN 0 AND 100),
  delai_paiement_jours integer CHECK (delai_paiement_jours >= 0),
  taux_tva_default numeric NOT NULL DEFAULT 20 CHECK (taux_tva_default BETWEEN 0 AND 100),
  valid_from date,
  valid_to date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tarification_client_client_id_idx
  ON public.tarification_client(client_id);

COMMIT;
